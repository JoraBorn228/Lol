local Services=game.ServerScriptService.Services
local Buffer=require(Services.ItemBuffer)
local State=require(Services.MachineState)
local Engine=require(Services.ProductionEngine)
local Recipes=require(game.ReplicatedStorage.Shared.Config.RecipeConfig)
local Config=require(game.ReplicatedStorage.Shared.Config.MachineConfig)
local checks=0
local function check(v,msg) assert(v,msg);checks+=1 end
for id,recipe in Recipes do
 if next(recipe.Inputs)==nil then continue end -- extraction is tested with finite nodes in Phase 6
 local state=State.new(Config.TestMachine);state.recipeId=id
 Engine.step(state,1)
 check(state.status=="WaitingInputs" and state.progress==0,id.." waits for input")
 check(Buffer.apply(state.input,recipe.Inputs),id.." load inputs")
 Engine.step(state,recipe.Duration/2)
 check(state.progress==recipe.Duration/2 and Buffer.total(state.output)==0,id.." partial progress")
 state.enabled=false;Engine.step(state,10)
 check(state.progress==recipe.Duration/2,id.." pause")
 state.enabled=true;Engine.step(state,recipe.Duration/2)
 check(state.progress==0 and Buffer.total(state.input)==0,id.." consumes exact batch")
 for product,amount in recipe.Outputs do check(state.output.items[product]==amount,id.." exact yield") end
 Engine.step(state,100)
 check(Buffer.total(state.output)>0 and state.status=="WaitingInputs",id.." no free repeats")
end
local state=State.new(Config.TestMachine)
Buffer.apply(state.input,{IronOre=2});Buffer.apply(state.output,{IronPlate=100})
Engine.step(state,10)
check(state.status=="OutputFull" and state.progress==0 and state.input.items.IronOre==2,"Backpressure preserves input/progress")
Buffer.apply(state.output,{IronPlate=-1});Engine.step(state,2)
check(state.input.items.IronOre==0 and state.output.items.IronPlate==100,"Resumes when one output slot freed")
local b=Buffer.new(3)
check(not Buffer.apply(b,{IronOre=4}),"Input capacity")
check(not Buffer.apply(b,{IronOre=-1}),"No negative stock")
check(not Buffer.apply(b,{Unknown=1}),"Unknown item")
check(not Buffer.apply(b,{Coal=0/0}),"Reject NaN")
check(Buffer.apply(b,{Coal=2}),"Valid add")
check(not Buffer.apply(b,{Coal=-3,IronOre=1}) and b.items.Coal==2 and not b.items.IronOre,"Atomic buffer batch")
local before=state.progress;Engine.step(state,0/0);Engine.step(state,-1);Engine.step(state,math.huge)
check(state.progress==before,"Invalid elapsed time ignored")
local Inventory=require(Services.InventoryService)
local Machines=require(Services.MachineService)
local actor=Instance.new("Folder")
local object=Instance.new("Part");object:SetAttribute("TemplateId","TestMachine")
Machines.attach(object)
local stored=Machines.get(object)
Buffer.apply(stored.input,{Coal=4});Buffer.apply(stored.output,{IronPlate=2})
check(Inventory.add(actor,"Coal",940),"Fill inventory to capacity")
check(not Machines.refundForRemoval(actor,object,1),"Full inventory refuses demolition refund")
check(Inventory.snapshot(actor).ConstructionUnit==20 and stored.input.items.Coal==4 and stored.output.items.IronPlate==2,"Failed refund preserves both sides")
check(Inventory.remove(actor,"Coal",100),"Make room for refund")
check(Machines.refundForRemoval(actor,object,1),"Refund entire machine contents atomically")
local stock=Inventory.snapshot(actor)
check(stock.ConstructionUnit==21 and stock.Coal==854 and stock.IronPlate==2,"Input output and construction credited exactly")
object:Destroy();actor:Destroy()
return {passed=checks}
